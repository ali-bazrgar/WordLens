import subprocess
import webbrowser
import time
import socket
from http.server import HTTPServer, SimpleHTTPRequestHandler

# پورت مورد نظر را مشخص می‌کنیم
PORT = 8000

def start_http_server(port):
    # اجرای سرور HTTP با استفاده از ماژول http.server
    # ما از HTTPServer و SimpleHTTPRequestHandler استفاده می‌کنیم تا کنترل بیشتری داشته باشیم،
    # اما برای سادگی و مشابه کد اصلی، می‌توانیم از روش زیر استفاده کنیم:

    # روش ساده‌تر (استفاده از دستور مستقیم در ترمینال یا اجرای اسکریپت)
    # اگر هدف شما فقط راه‌اندازی سرور است، می‌توانید این بخش را جایگزین کنید:
    print(f"سرور روی پورت {port} اجرا می‌شود...")

    # استفاده از subprocess برای اجرای دستور استاندارد Python
    # توجه: در سیستم‌های مختلف ممکن است نیاز به تنظیمات دسترسی (Permissions) داشته باشید.
    try:
        # اجرای سرور با استفاده از ماژول http.server
        # این روش کمی متفاوت از کد اصلی شماست که سعی می‌کرد پورت را پویا پیدا کند.
        # برای اطمینان از اینکه سرور روی پورت 8000 اجرا شود، معمولاً باید یک اسکریپت جداگانه یا دستور سیستمی استفاده شود.

        # اجرای مستقیم سرور با استفاده از ماژول http.server (به عنوان مثال)
        # در اینجا ما از روشی که شما استفاده کردید برای اطمینان از اجرای صحیح استفاده می‌کنیم:
        subprocess.Popen(['python', '-m', 'http.server', str(port)])

    except Exception as e:
        print(f"خطا در اجرای سرور: {e}")


# --- اجرای اصلی ---

print(f"در حال راه‌اندازی سرور روی پورت ثابت: {PORT}")

# اجرای دستور برای شروع سرور (این دستور به فرآیند جدیدی اضافه می‌شود)
start_http_server(PORT)

# صبر برای راه‌اندازی سرور
time.sleep(2)

